# frozen_string_literal: true

module FeatureFlags
  # Renders app/frontend/types/generated/featureFlags.ts: the names useFeatureFlag
  # accepts, so a misspelled flag fails `tsc`. Only `client: true` flags are
  # listed, camelized as DeepKeyCamelizer delivers them in the `features` prop.
  # Written by `bin/rails feature_flags:typescript`, which `typelizer:generate`
  # runs too; test/config/feature_flags_typescript_test.rb keeps it current.
  module Typescript
    OUTPUT_PATH = Rails.root.join("app/frontend/types/generated/featureFlags.ts")

    HEADER = <<~TS
      // DO NOT MODIFY: generated by `bin/rails feature_flags:typescript` from config/feature_flags.yml.
      //
      // The flags declared `client: true`, as the `features` shared prop names them.
    TS

    module_function

    def render(registry = FeatureFlags.registry)
      names = registry.definitions.select(&:client?).map { |definition| definition.key.to_s.camelize(:lower) }.sort

      union = if names.empty?
        " never;\n"
      else
        "\n#{names.map { |name| "  | '#{name}'" }.join("\n")};\n"
      end

      "#{HEADER}export type FeatureFlagName =#{union}"
    end

    def write(path = OUTPUT_PATH, registry: FeatureFlags.registry)
      FileUtils.mkdir_p(File.dirname(path))
      File.write(path, render(registry))
      path
    end
  end
end
